import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
import path from 'node:path';

const browserRoot = process.env.ACADEMY_BROWSER_ROOT;
if (!browserRoot) throw new Error('ACADEMY_BROWSER_ROOT must point to the isolated Playwright installation');
const require = createRequire(path.join(browserRoot, 'package.json'));
const { chromium } = require('playwright');
const base = process.env.ACADEMY_BASE_URL ?? 'http://127.0.0.1:3100';
const browser = await chromium.launch({ headless: true });
const context = await browser.newContext({ viewport: { width: 1440, height: 900 }, reducedMotion: 'reduce' });
const page = await context.newPage();
const errors = [];
page.on('pageerror', (error) => errors.push(error.message));
const wait = (locator) => locator.waitFor({ state: 'visible', timeout: 20000 });
const btn = (name) => page.getByRole('button', { name, exact: true });
try {
  await page.goto(base, { waitUntil: 'networkidle' });
  await wait(page.getByRole('heading', { name: /JSX: Describe a UI/ }));
  await wait(btn('Read lesson'));
  assert.equal(await page.locator('iframe[title="Live React JSX Sandbox"]').count(), 0, 'Reader must not mount a code sandbox');
  await btn('Notes').click();
  await page.getByLabel(/Private notes/).fill('Browser smoke note');
  await page.reload({ waitUntil: 'networkidle' });
  await btn('Notes').click();
  assert.equal(await page.getByLabel(/Private notes/).inputValue(), 'Browser smoke note');
  await btn('Notes').click();
  await btn('Practice').click();
  const editor = page.getByLabel('Interactive code editor');
  const frame = page.frameLocator('iframe[title="Live React JSX Sandbox"]');
  await wait(editor);
  await wait(frame.getByRole('heading', {name:'Engineering team', exact:true}));
  assert.equal(await page.locator('iframe[title="Live React JSX Sandbox"]').getAttribute('sandbox'), 'allow-scripts');
  await editor.fill("const title = 'First run'; export default function App() { return <h1>{title}</h1>; }");
  await wait(frame.getByRole('heading', {name:'First run'}));
  await editor.fill("const title = 'Second run'; export default function App() { return <h1>{title}</h1>; }");
  await wait(frame.getByRole('heading', {name:'Second run'}));
  await btn('Mobile').click();
  await wait(frame.getByRole('heading', {name:'Second run'}));
  await btn('Read lesson').click();
  assert.equal(await page.locator('iframe[title="Live React JSX Sandbox"]').count(), 0);
  await page.getByRole('button', {name:'Search curriculum and references'}).click();
  await wait(page.getByRole('dialog', {name:'Search academy'}));
  await page.getByLabel('Global curriculum and reference search').fill('safeParse');
  await wait(page.getByRole('dialog').getByRole('button', {name:/safeParse/}).first());
  await page.keyboard.press('Escape');
  await page.getByRole('dialog').waitFor({state:'hidden'});

  await page.goto(base + '/learn/06.01.01');
  await wait(page.getByRole('heading', {name:'The problem we\'re solving', exact:true}));
  await page.getByRole('radio', {name:/Tooling compiles JSX/}).check();
  await btn('Check answer').click();
  await wait(page.getByText('Correct — you identified the concept.'));
  await page.goto(base + '/reference/zod-safeparse');
  await wait(page.getByRole('heading',{name:/Zod 4: schema.safeParse/}));
  await page.goto(base + '/learn/01.01.01');
  assert.match(await page.locator('meta[name="robots"]').getAttribute('content'), /noindex/);
  await wait(page.getByText('Planned lesson — not published.', {exact:true}));
  await page.goto(base + '/learn/00.01.01');
  await wait(page.getByRole('heading',{name:'What runs in a browser vs on a server?',exact:true}));
  await page.getByRole('radio',{name:/Only in the trusted server environment/}).check();
  await btn('Check answer').click();
  const gate = page.getByRole('region',{name:'Lesson completion'});
  assert.equal(await btn('Mark complete').isEnabled(),false);
  for (const checkbox of await gate.getByRole('checkbox').all()) await checkbox.check();
  await btn('Mark complete').click();
  await wait(btn('Completed'));
  await page.reload({waitUntil:'networkidle'});
  await wait(btn('Completed'));
  await page.getByRole('link',{name:/Next: Client server lifecycle/}).click();
  await wait(page.getByRole('heading',{name:'Client–server lifecycle: follow a real request',exact:true}));
  for (const id of ["00.01.03","00.01.04","00.01.05","00.01.06","00.01.07","00.01.08","00.02.01","00.02.02","00.02.03","00.02.04","00.02.05","00.02.06","00.02.07","00.02.08","00.03.01","00.03.02","00.03.03","00.03.04","00.03.05","00.03.06","00.03.07","00.03.08"]) {
    const result = await page.goto(base+'/learn/'+id);
    assert.equal(result.status(),200);
    assert.match(await page.locator('meta[name="robots"]').getAttribute('content'), /^index/);
    await wait(page.getByRole('region',{name:'Lesson completion'}));
    await wait(page.getByRole('heading',{name:'Build the mental model',exact:true}));
    assert.equal(await page.getByRole('button',{name:'Mark complete'}).isEnabled(), false);
  }
  await page.setViewportSize({width: 390,height:844});
  await page.goto(base+'/?lesson=06.01.01&mode=practice');
  await wait(btn('Practice'));
  await btn('Output').click();
  await wait(page.frameLocator('iframe[title="Live React JSX Sandbox"]').getByRole('heading',{name:'Engineering team',exact:true}));
  await btn('Read lesson').click();
  await btn('Toggle curriculum navigation').click();
  await wait(page.getByLabel('Filter navigation list'));
  await btn('Toggle curriculum navigation').click();
  assert.equal(await btn('Toggle curriculum navigation').getAttribute('aria-expanded'), 'false');
  assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth <= window.innerWidth), 'Mobile page must not overflow horizontally');
  assert.deepEqual(errors, [], 'No unhandled page errors');
  console.log('Browser smoke passed: reader, practice, JSX reruns, notes, search, MDX quiz, references, noindex, mobile');
} finally {
  await context.close();
  await browser.close();
}
