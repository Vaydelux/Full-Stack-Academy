import assert from 'node:assert/strict';
import {readFileSync,existsSync} from 'node:fs';
import {execFileSync} from 'node:child_process';
import {fileURLToPath} from 'node:url';
import {join} from 'node:path';
import {projectPersistenceChain} from './p3-source-rehearsal.mjs';
const root=fileURLToPath(new URL('../',import.meta.url));
const git=(...args)=>execFileSync('git',args,{cwd:root,encoding:'utf8',timeout:30000,maxBuffer:32*1024*1024});
const head=git('rev-parse','HEAD');const index=git('ls-files','--stage','-z');
assert.equal(git('status','--porcelain=v1','--untracked-files=all'),'');
const read=p=>readFileSync(join(root,p),'utf8'),exists=p=>existsSync(join(root,p));
const checkpoint=JSON.parse(read('docs/checkpoint.json'));
assert.equal(checkpoint.snapshot.publishedLessons,338,'Standalone source audit expects original published baseline');
const result=projectPersistenceChain({baseline:338,catalog:JSON.parse(read('data/curriculum.json')),read,exists});
assert.equal(result.p4.reviewOverlayTarget,442);assert.equal(result.p4.canonicalRoadmapTarget,490);
assert.equal(result.p4.predecessorFixturePresent,false);assert.equal(result.p4.blockedManualWrappers,64);
assert.equal(git('rev-parse','HEAD'),head);assert.equal(git('ls-files','--stage','-z'),index);
assert.equal(git('status','--porcelain=v1','--untracked-files=all'),'');
console.log(JSON.stringify(result,null,2));
